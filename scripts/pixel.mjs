/** Advance of one character in font pixels (5 wide + 1 gap). The font is monospaced so typing can step by character. */
export const ADV = 6;
export const textW = (str, s) => str.length * ADV * s - s;

/** Rows of a bitmap ('1'/'X' = on) to a path, merging horizontal runs. */
export function bitmapPath(rows, x, y, s) {
  let d = '';
  rows.forEach((row, r) => {
    let c = 0;
    while (c < row.length) {
      if (row[c] === '1' || row[c] === 'X') {
        let e = c;
        while (e < row.length && (row[e] === '1' || row[e] === 'X')) e++;
        d += `M${x + c * s} ${y + r * s}h${(e - c) * s}v${s}h${-(e - c) * s}z`;
        c = e;
      } else c++;
    }
  });
  return d;
}

export function textPath(str, x, y, s) {
  let d = '';
  [...str.toUpperCase()].forEach((ch, i) => {
    const g = G[ch];
    if (!g) throw new Error(`no glyph for "${ch}" in "${str}"`);
    d += bitmapPath(g, x + i * ADV * s, y, s);
  });
  return d;
}

export const text = (str, x, y, s, attrs = '') => `<path d="${textPath(str, x, y, s)}"${attrs ? ` ${attrs}` : ''}/>`;

